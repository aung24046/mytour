BEGIN;

ALTER TABLE public.organizations
  -- คีย์พรีเซ็ต: 'ocean' | 'slate' | 'mono' | 'navy' (ดู THEME_PRESETS)
  -- ค่าที่ไม่รู้จักจะถูก resolveTheme() ตกกลับไปที่ 'ocean' เอง
  ADD COLUMN IF NOT EXISTS theme_preset      text NOT NULL DEFAULT 'ocean',
  -- สีแบรนด์แบบ '#0891b2' — NULL = ใช้สีของพรีเซ็ต
  -- ระบบคำนวณเฉดที่เหลือ (hover/light/lighter/deep/start) จากสีนี้เอง
  -- และเข้มขึ้นให้อัตโนมัติถ้าตัวหนังสือขาวบนพื้นนี้อ่านไม่ออก
  ADD COLUMN IF NOT EXISTS theme_brand_color text,
  ADD COLUMN IF NOT EXISTS theme_updated_at  timestamptz;

COMMIT;

