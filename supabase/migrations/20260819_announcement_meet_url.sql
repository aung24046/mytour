-- ⚠️ ที่ต้องมีคอลัมน์นี้เพราะออกแบบรอบแรกพลาด:
--    ปุ่ม "แชร์" ในแอป Google Maps สร้างลิงก์ย่อ maps.app.goo.gl ให้เป็นค่าเริ่มต้น
--    ซึ่งเป็นสิ่งที่ทีมงานได้มาเป็นอันดับแรกและใช้กันจริง ไม่ใช่เคสหายาก
--    แต่ลิงก์ย่อ "ไม่มีพิกัดอยู่ข้างในตัวมันเอง" ต้องยิง HTTP ตามไปดูปลายทางถึงจะรู้
--    ซึ่งเบราว์เซอร์ทำเองไม่ได้ (ติด CORS) รอบแรกจึงปฏิเสธลิงก์แบบนี้ทิ้ง
--    ผลคือทีมงานวางลิงก์ กดส่ง แล้วหมุดหายเงียบ ลูกทัวร์ไม่มีปุ่มให้กด
--
-- ทางออกที่เลือก: เก็บลิงก์ไว้ทั้งอันแล้วให้ลูกทัวร์กดเปิด Google Maps เอง
--   ได้     — รับลิงก์ได้ทุกแบบ รวมถึงลิงก์ย่อ ลิงก์ place ลิงก์แผนที่เจ้าอื่น
--   เสีย    — ไม่มีพิกัดให้คำนวณ ปุ่มจึงพาไปหน้าหมุดเฉยๆ ลูกทัวร์ต้องกด "เส้นทาง"
--             ต่ออีกหนึ่งครั้งในแอป Maps (แทนที่จะเห็น "เดิน 14 นาที" ทันที)
--   ทางที่ดีกว่ายังอยู่ — ปุ่ม "ปักตรงที่ฉันยืนอยู่" ให้พิกัดจริง ใช้เมื่อยืนอยู่จุดนั้น
--
-- ไม่เลือกทำ edge function ไปตามลิงก์ย่อ เพราะเพิ่มของที่ต้องดูแลและพังได้
-- ถ้า Google เปลี่ยนรูปแบบ redirect — ไม่คุ้มกับการประหยัดการกดหนึ่งครั้ง
--
-- idempotent รันซ้ำได้
-- =====================================================================

BEGIN;

ALTER TABLE public.announcements
  ADD COLUMN IF NOT EXISTS meet_url text;

DO $$
BEGIN
  -- ต้องเป็นลิงก์จริงเท่านั้น กันข้อความหลงเข้ามาแล้วกลายเป็นปุ่มที่กดแล้วไม่ไปไหน
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'announcements_meet_url_check') THEN
    ALTER TABLE public.announcements ADD CONSTRAINT announcements_meet_url_check
      CHECK (meet_url IS NULL OR meet_url ~* '^https?://[^[:space:]]+$');
  END IF;
END $$;

COMMENT ON COLUMN public.announcements.meet_url IS
  'ลิงก์จุดนัดพบสำหรับกรณีที่แกะพิกัดไม่ได้ (ลิงก์ย่อ maps.app.goo.gl ฯลฯ) — ถ้ามี meet_lat/meet_lng ให้ใช้พิกัดก่อน';

COMMIT;

