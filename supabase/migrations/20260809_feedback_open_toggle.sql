-- =====================================================================
-- สวิตช์ "เปิดให้ประเมินในแอป" ต่อทริป — tours.feedback_open
--
-- ที่มา: ฟอร์มประเมิน (/t/:code/feedback) มีมาตั้งแต่ต้น แต่ไม่มีทางเข้าจากในแอปเลย
-- ทางเข้าเดียวคือ QR บนใบประเมินกระดาษ ลูกทัวร์ที่ไม่ได้รับใบจึงหาไม่เจอ
-- ตอนนี้เพิ่มการ์ดชวนประเมินบนหน้าแรกลูกทัวร์ — แต่ต้องมีสวิตช์คุม
-- ไม่งั้นการ์ดจะโผล่ตั้งแต่วันแรกของทริป ซึ่งเป็นการชวนประเมินก่อนเที่ยวจบ
--
-- ⚠️ ทำไมต้องมีคอลัมน์นี้ ทั้งที่ดู is_active ของคำถามก็พอ
--    เพราะสองอย่างนี้คนละความหมาย:
--      is_active   = "คำถามข้อนี้ใช้อยู่ไหม" (แอดมินตั้งฟอร์มล่วงหน้าตั้งแต่ก่อนออกทริป)
--      feedback_open = "ถึงเวลาให้ลูกทัวร์ตอบหรือยัง"
--    ถ้าใช้ is_active ตัวเดียว แอดมินจะเตรียมฟอร์มล่วงหน้าไม่ได้เลย
--    ต้องรอไปตั้งคำถามตอนวันสุดท้ายบนรถ ซึ่งเป็นเวลาที่ยุ่งที่สุดของทริป
--
-- ⚠️ DEFAULT false โดยตั้งใจ — ทริปเก่าที่รันอยู่จะไม่มีการ์ดโผล่ขึ้นมาเอง
--    หลัง deploy ลูกทัวร์กลางทริปไม่ควรเห็นอะไรเปลี่ยนจนกว่าทีมงานจะกดเปิด
--
-- หน้าที่ปิด/เปิด: staff → ฟอร์ม → แท็บ "ฟอร์ม Feedback" (capability 'form.assign' = lead)
-- หน้าที่อ่านค่า: src/components/common/GuestHome.jsx (การ์ดชวนประเมิน)
--
-- หมายเหตุ: การปิดสวิตช์ "ซ่อนทางเข้า" เท่านั้น ไม่ได้ล็อกหน้า /feedback
-- ใครถือลิงก์/QR กระดาษอยู่ยังตอบได้ตามเดิม — เจตนาคือไม่ให้ QR ที่พิมพ์แจกไปแล้วตายกลางทริป
-- =====================================================================

BEGIN;

ALTER TABLE public.tours
  -- true = แสดงการ์ดชวนประเมินบนหน้าแรกลูกทัวร์
  ADD COLUMN IF NOT EXISTS feedback_open      boolean NOT NULL DEFAULT false,
  -- เวลาที่กดเปิดครั้งล่าสุด — ไว้ตอบคำถาม "เปิดให้ประเมินตอนไหน" ในรายงานสรุป
  ADD COLUMN IF NOT EXISTS feedback_opened_at timestamptz;

-- realtime — ต้องมี ไม่งั้นการ์ดจะไม่ขึ้นจนกว่าลูกทัวร์จะรีเฟรชเอง
--
-- ⚠️ ถ้าลืมบรรทัดนี้ โค้ดฝั่งแอปจะ "ดูเหมือนทำงาน" — supabase.channel().on()
--    ไม่ error เวลาตารางไม่ได้อยู่ใน publication มันแค่เงียบไปเฉยๆ
--    อาการที่เจอหน้างานคือหัวหน้าทัวร์กดเปิดแล้วประกาศบนรถ แต่ลูกทัวร์ไม่เห็นอะไร
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'tours'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.tours;
  END IF;
END $$;

COMMIT;

